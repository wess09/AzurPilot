import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'
import { expect, test } from '@playwright/test'

test('从 WebUI 安装主题和功能包并跨浏览器恢复', async ({page, browser, baseURL}, info) => {
  await page.route('https://www.clarity.ms/**', route => route.abort())
  await page.goto('/#/plugins')
  await expect(page.getByRole('heading', {name: '已安装插件'})).toBeVisible()
  const examples = resolve('plugin-sdk/examples')
  for (const name of ['workbench', 'task-favorites']) {
    const destination = info.outputPath(name + '.apu')
    execFileSync('uv', ['run', 'python', '-m', 'dev_tools.pack_apu', resolve(examples, name), destination], {cwd: '..'})
    await page.locator('input[type=file]').setInputFiles(destination)
    const card = page.locator('article').filter({has: page.getByRole('heading', {name: name === 'workbench' ? '工作台' : '任务收藏', exact: true})})
    await expect(card.getByText(/已停用/)).toBeVisible()
    await card.getByRole('button', {name: '启用', exact: true}).click()
    await expect(card.getByText(/已启用/)).toBeVisible()
  }

  await page.goto('/#/i/testpilot/overview')
  await expect(page.locator('.workbench-shell')).toBeVisible()
  const widget = page.locator('[data-apu-component="scheduler"]')
  await expect(widget).toHaveCSS('border-radius', '4px')
  await expect(widget).not.toHaveClass(/scheduler-widget/)
  const icon = widget.locator('img')
  await expect.poll(() => icon.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  await expect(page.locator('.monitor-panel')).toBeVisible()
  await expect(page.frameLocator('iframe[title="收藏任务"]').getByRole('button', {name: '收藏', exact: true})).toBeVisible()
  await page.setViewportSize({width: 390, height: 844})
  await expect(page.locator('.workbench-shell')).toBeVisible()
  expect(await page.locator('.workbench-content').evaluate(main => main.scrollWidth - main.clientWidth)).toBeLessThanOrEqual(1)
  await page.setViewportSize({width: 1440, height: 1100})
  await expect(page.getByRole('link', {name: '任务收藏', exact: true})).toBeVisible()
  await page.getByRole('link', {name: '任务收藏', exact: true}).click()
  const view = page.frameLocator('iframe[title="任务收藏"]')
  await expect(view.getByRole('button', {name: '收藏', exact: true})).toBeVisible()
  await expect(view.getByRole('combobox').locator('option').first()).toBeAttached()
  const selected = await view.getByRole('combobox').inputValue()
  await view.getByRole('button', {name: '收藏', exact: true}).click()
  await expect(view.getByRole('listitem')).toContainText(selected)
  await page.reload()
  await expect(view.getByRole('listitem')).toContainText(selected)

  const second = await browser.newContext({baseURL, locale: 'zh-CN'})
  try {
    const other = await second.newPage()
    await other.route('https://www.clarity.ms/**', route => route.abort())
    await other.goto('/#/i/testpilot/plugins/task-favorites/favorites')
    await expect(other.frameLocator('iframe[title="任务收藏"]').getByRole('listitem')).toContainText(selected)
    await other.goto('/#/plugins')
    await other.locator('article').filter({hasText: '任务收藏'}).getByRole('button', {name: '停用', exact: true}).click()
    await expect(page.getByText('插件页面不可用。')).toBeVisible()
  } finally { await second.close() }

  await page.goto('/#/plugins')
  await page.locator('article').filter({hasText: '工作台'}).getByRole('button', {name: '停用', exact: true}).click()
  await page.goto('/#/i/testpilot/overview')
  await expect(page.locator('.modern-shell')).toBeVisible()
  await expect(page.locator('.apu-scheduler-icon')).toHaveCount(0)

  await page.goto('/#/plugins')
  const destination = info.outputPath('compact-scheduler.apu')
  execFileSync('uv', ['run', 'python', '-m', 'dev_tools.pack_apu', resolve(examples, 'compact-scheduler'), destination], {cwd: '..'})
  await page.locator('input[type=file]').setInputFiles(destination)
  const scheduler = page.locator('article').filter({hasText: '舰桥调度器'})
  await scheduler.getByRole('button', {name: '启用', exact: true}).click()
  await expect(scheduler.getByText(/已启用/)).toBeVisible()
  await page.goto('/#/i/testpilot/overview')
  const replacement = page.frameLocator('.apu-scheduler iframe')
  const start = replacement.getByRole('button', {name: '启动调度器'})
  await expect(start).toBeEnabled()
  const navigation = page.frameLocator('.apu-navigation iframe')
  await expect(navigation.getByRole('button', {name: '插件', exact: true})).toBeVisible()
  await start.click()
  // The E2E server intercepts the host RPC and prevents real game actions.
  await expect(page.getByText('浏览器测试服务不会执行游戏任务')).toBeVisible()
  await page.goto('/#/i/testpilot/task/Guild')
  await expect(page.locator('.task-config-legacy')).toBeVisible()
  await navigation.getByRole('button', {name: '插件', exact: true}).click()
  await expect(page.getByRole('heading', {name: '已安装插件'})).toBeVisible()
})
